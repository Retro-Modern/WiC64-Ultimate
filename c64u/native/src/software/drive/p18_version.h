#ifndef P18_WIC64_VERSION_H
#define P18_WIC64_VERSION_H

// Public compatibility target and U64 release identity are separate. The
// canonical wire version must retain the format used by existing CC clients.
#define P18_VERSION_STRINGIFY_INNER(value) #value
#define P18_VERSION_STRINGIFY(value) P18_VERSION_STRINGIFY_INNER(value)
#define P18_WIC64_MAJOR 2
#define P18_WIC64_MINOR 4
#define P18_WIC64_PATCH 4
#define P18_WIC64_REVISION 1
#define P18_PORT64_MAJOR 1
#define P18_PORT64_MINOR 1
#define P18_PORT64_PATCH 4
#define P18_U64_BUILD_MAJOR 0
#define P18_U64_BUILD_MINOR 19
#define P18_U64_BUILD_PATCH 0
#define P18_U64_BUILD_REVISION 0
#define P18_RELEASE_STAGE "beta"
#define P18_RELEASE_CANDIDATE 2

#define P18_WIC64_VERSION P18_VERSION_STRINGIFY(P18_WIC64_MAJOR) "." P18_VERSION_STRINGIFY(P18_WIC64_MINOR) "." P18_VERSION_STRINGIFY(P18_WIC64_PATCH)
#define P18_PORT64_VERSION P18_VERSION_STRINGIFY(P18_PORT64_MAJOR) "." P18_VERSION_STRINGIFY(P18_PORT64_MINOR) "." P18_VERSION_STRINGIFY(P18_PORT64_PATCH)
#define P18_COMPATIBILITY_VERSION P18_WIC64_VERSION "-" P18_VERSION_STRINGIFY(P18_WIC64_REVISION)
#define P18_U64_BUILD_VERSION P18_VERSION_STRINGIFY(P18_U64_BUILD_MAJOR) "." P18_VERSION_STRINGIFY(P18_U64_BUILD_MINOR) "." P18_VERSION_STRINGIFY(P18_U64_BUILD_PATCH)
#define P18_U64_BUILD_ID P18_U64_BUILD_VERSION "-c64u-b2"
#define P18_RELEASE_LABEL "C64U Beta " P18_VERSION_STRINGIFY(P18_RELEASE_CANDIDATE)
// W64I clients require the canonical U64 provider tag, also on C64 Ultimate.
#define P18_WIRE_VERSION P18_COMPATIBILITY_VERSION " (U64 " P18_U64_BUILD_VERSION ")"
#define P18_COMPATIBILITY_REFERENCE "WiC64" P18_WIC64_VERSION "/PORT64" P18_PORT64_VERSION "-C1"
#define P18_PUBLIC_DISPLAY_VERSION "WiC64 " P18_WIC64_VERSION " / PORT64 " P18_PORT64_VERSION " " P18_RELEASE_LABEL
#define P18_STATUS_TITLE P18_PUBLIC_DISPLAY_VERSION
#define P18_DIAGNOSTIC_TITLE "Diagnostic " P18_WIC64_VERSION " / C64U " P18_U64_BUILD_VERSION " B" P18_VERSION_STRINGIFY(P18_RELEASE_CANDIDATE)
#define P18_TLS_DETAILS_TITLE "TLS Details " P18_WIC64_VERSION " / C64U " P18_U64_BUILD_VERSION " B" P18_VERSION_STRINGIFY(P18_RELEASE_CANDIDATE)
#define P18_HTTP_USER_AGENT "WiC64/" P18_WIC64_VERSION " (C64 Ultimate; " P18_U64_BUILD_VERSION ")"

#endif
