"""Regenerate the supplied helper, portal and certificate source headers."""
from pathlib import Path
import argparse
import hashlib
import re
import shutil
import ssl
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent


def array(data, spaced=False):
    separator = ', ' if spaced else ','
    return '\n'.join('    ' + separator.join('0x%02x' % b for b in data[n:n+16]) + ','
                     for n in range(0, len(data), 16))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--acme', default='acme')
    a = p.parse_args()
    acme = shutil.which(a.acme)
    if not acme:
        p.error('Install external ACME or pass --acme /path/to/acme')
    drive = ROOT / 'native/software/drive'
    with tempfile.TemporaryDirectory(prefix='wic64-assets-') as scratch:
        work = Path(scratch)
        rom, symbols = work / 'helper.rom', work / 'helper.sym'
        subprocess.run([acme, '-f', 'plain', '-o', str(rom), '-l', str(symbols),
                        str(ROOT / 'firmware_assets/helper/drive_service.asm')], check=True)
        data = rom.read_bytes()
        found = re.findall(r'^\s*helper_session\s*=\s*\$([\da-fA-F]+)\b', symbols.read_text(), re.M)
        if len(data) != 16384 or len(found) != 1:
            raise ValueError('Invalid helper image')
        offset = int(found[0], 16) - 0xc000
        if not 0 <= offset <= len(data)-8 or data[offset:offset+8] != bytes(8):
            raise ValueError('Invalid helper nonce slot')
        text = ('// Generated by build_assets.py from the supplied assembly.\n'
                '#ifndef P08_EMBEDDED_HELPER_H\n#define P08_EMBEDDED_HELPER_H\n#include <stdint.h>\n'
                'static const uint8_t p08_helper_rom[16384] = {\n' + array(data, True) + '\n};\n'
                'static const unsigned P08_HELPER_SESSION_OFFSET = %u;\n' % offset +
                'static const char P08_HELPER_SHA256[] = "%s";\n#endif\n' % hashlib.sha256(data).hexdigest())
        (drive / 'p08_embedded_helper.h').write_text(text)
        portal = ROOT / 'firmware_assets/portal'
        prg = work / 'portal.prg'
        subprocess.run([acme, '-I', str(portal), '-I', str(portal / 'examples'),
                        '-f', 'cbm', '-o', str(prg),
                        str(portal / 'examples/04-enter-portal/main.asm')], check=True)
        data = prg.read_bytes()
        if data[:2] != b'\x01\x08':
            raise ValueError('Invalid portal load address')
        text = ('#ifndef P12_EMBEDDED_PORTAL_H\n#define P12_EMBEDDED_PORTAL_H\n#include <stdint.h>\n'
                'static const unsigned P12_PORTAL_SIZE=%d;\n' % len(data) +
                'static const char P12_PORTAL_SHA256[]="%s";\n' % hashlib.sha256(data).hexdigest() +
                'static const uint8_t p12_portal_prg[P12_PORTAL_SIZE]={\n' + array(data) + '\n};\n#endif\n')
        (drive / 'p12_embedded_portal.h').write_text(text)
    pem = (ROOT / 'certificates/cacert.pem').read_bytes()
    certificates = [ssl.PEM_cert_to_DER_cert(p.decode('ascii')) for p in
                    re.findall(b'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', pem, re.S)]
    if not certificates or len(set(certificates)) != len(certificates):
        raise ValueError('Invalid certificate bundle')
    indices, offset = [], 0
    for cert in certificates:
        if len(cert) > 65535:
            raise ValueError('Oversized certificate')
        indices.append((offset, len(cert)))
        offset += len(cert)
    text = ('// Generated from certificates/cacert.pem; Mozilla CA data, MPL-2.0.\n'
            '#ifndef P14_TRUST_ROOTS_H\n#define P14_TRUST_ROOTS_H\n#include <stdint.h>\nnamespace p14 {\n'
            'static const unsigned TRUST_ROOT_COUNT=%d;\n' % len(certificates) +
            'struct TrustRootIndex {uint32_t offset;uint16_t length;};\nstatic const TrustRootIndex trust_root_index[]={\n' +
            '\n'.join(' {%du,%du},' % i for i in indices) +
            '\n};\nstatic const uint8_t trust_root_der[]={\n' + array(b''.join(certificates)) + '\n};\n}\n#endif\n')
    (drive / 'p14_trust_roots.h').write_text(text)
    print('Current source headers regenerated.')


if __name__ == '__main__':
    main()
